#!/usr/bin/env python3
"""CLI tests for set-theme, run against a temporary home, state and checkout."""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


SCRIPT = Path(__file__).with_name("set-theme")
REPO_ROOT = Path(__file__).resolve().parent.parent
THEMES = ("catppuccin-macchiato", "catppuccin-mocha", "dark-2026", "default-dark-modern")


class SetThemeTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        fixture = Path(self.temporary.name).resolve()
        self.home = fixture / "home"
        self.state_home = fixture / "state"
        self.root = fixture / "dotfiles/macos"
        self.home.mkdir()
        self.state = self.state_home / "dotfiles/theme"
        (self.root / ".config/ghostty").mkdir(parents=True)
        (self.root / ".config/ghostty/base").write_text("font-size = 14\n", encoding="utf-8")
        (self.root / ".config/lazydocker").mkdir(parents=True)
        (self.root / ".config/lazydocker/base.yml").write_text("# base\n# >>> theme\n# <<< theme\nlogs: {}\n", encoding="utf-8")
        (self.root / ".config/superfile").mkdir(parents=True)
        (self.root / ".config/superfile/base.toml").write_text("editor = ''\n", encoding="utf-8")
        for name in ("catppuccin-macchiato", "dark-2026"):
            self.add_theme(name)
        # Stand in for the links check-links --create makes.
        for directory in (".config/lazygit", ".tmux/themes", ".config/lazydocker/themes"):
            (self.home / directory).parent.mkdir(parents=True, exist_ok=True)
            (self.home / directory).symlink_to(self.root / directory)

    def add_theme(
        self, name: str, tools: tuple[str, ...] = ("starship", "lazygit", "tmux", "ghostty", "lazydocker", "superfile")
    ) -> None:
        files = {
            "lazydocker": f".config/lazydocker/themes/{name}.yml",
            "superfile": f".config/superfile/theme/{name}.toml",
            "starship": f".config/starship.{name}.toml",
            "lazygit": f".config/lazygit/themes/{name}.yml",
            "tmux": f".tmux/themes/{'catppuccin' if name == 'catppuccin-mocha' else name}.conf",
            "ghostty": f".config/ghostty/themes/{name}",
        }
        for tool in tools:
            path = self.root / files[tool]
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(f"{name}\n", encoding="utf-8")
            if tool in ("starship", "ghostty", "superfile"):
                (self.home / files[tool]).parent.mkdir(parents=True, exist_ok=True)
                (self.home / files[tool]).symlink_to(path)

    def tracked(self) -> dict[str, bytes]:
        checkout = self.root.parent
        return {str(path): path.read_bytes() for path in sorted(checkout.rglob("*")) if path.is_file()}

    def run_theme(self, *args: str, root: Path | None = None, **env: str) -> subprocess.CompletedProcess[str]:
        environment = {**os.environ, "XDG_STATE_HOME": str(self.state_home), **env}
        return subprocess.run(
            [str(SCRIPT), "--home", str(self.home), "--root", str(root or self.root), *args],
            text=True,
            capture_output=True,
            env=environment,
        )

    def exports(self) -> dict[str, str]:
        result = self.run_theme("--env")
        self.assertEqual(result.returncode, 0, result.stderr)
        shell = subprocess.run(
            ["zsh", "-fc", f'{result.stdout}\nprint -r -- "$STARSHIP_CONFIG"; print -r -- "$LG_CONFIG_FILE"'],
            text=True,
            capture_output=True,
            check=True,
        )
        starship, lazygit = shell.stdout.splitlines()
        return {"STARSHIP_CONFIG": starship, "LG_CONFIG_FILE": lazygit}

    def test_named_switch_saves_the_theme_for_new_shells(self) -> None:
        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.state.read_text(encoding="utf-8"), "dark-2026\n")
        self.assertEqual(
            self.exports(),
            {
                "STARSHIP_CONFIG": f"{self.home}/.config/starship.dark-2026.toml",
                "LG_CONFIG_FILE": f"{self.home}/.config/lazygit/config.yml,{self.home}/.config/lazygit/themes/dark-2026.yml",
            },
        )

    def test_switch_generates_tmux_conf_with_the_historical_mocha_name(self) -> None:
        self.add_theme("catppuccin-mocha")

        result = self.run_theme("catppuccin-mocha")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            (self.home / ".tmux.conf").read_text(encoding="utf-8"),
            "# Generated by macos/scripts/set-theme from macos/.tmux/base.conf; edits are overwritten.\n"
            "set -g @theme catppuccin\n"
            "source-file ~/.tmux/base.conf\n",
        )

    def test_switch_generates_ghostty_config_from_its_base(self) -> None:
        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            (self.home / ".config/ghostty/config").read_text(encoding="utf-8"),
            "# Generated by macos/scripts/set-theme from macos/.config/ghostty/base; edits are overwritten.\n"
            "font-size = 14\n"
            'theme = "dark-2026"\n',
        )

    def test_switch_generates_lazydocker_config_with_the_variant_body_between_the_markers(self) -> None:
        (self.root / ".config/lazydocker/themes/dark-2026.yml").write_text(
            "# Dark 2026\n\ngui:\n  theme: {} # kept\n\n", encoding="utf-8"
        )

        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            (self.home / ".config/lazydocker/config.yml").read_text(encoding="utf-8"),
            "# Generated by macos/scripts/set-theme from macos/.config/lazydocker/base.yml; edits are overwritten.\n"
            "# base\n"
            "# >>> theme: dark-2026\n"
            "gui:\n"
            "  theme: {} # kept\n"
            "# <<< theme\n"
            "logs: {}\n",
        )

    def test_switch_generates_superfile_config_from_its_base(self) -> None:
        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            (self.home / ".config/superfile/config.toml").read_text(encoding="utf-8"),
            "# Generated by macos/scripts/set-theme from macos/.config/superfile/base.toml; edits are overwritten.\n"
            "theme = 'dark-2026'\n"
            "editor = ''\n",
        )

    def test_switch_migrates_old_repo_links_without_touching_tracked_files(self) -> None:
        for target in (".tmux.conf", ".config/ghostty/config"):
            (self.root / target).write_text("tracked\n", encoding="utf-8")
            (self.home / target).symlink_to(self.root / target)
        before = self.tracked()

        for name in ("dark-2026", "catppuccin-macchiato"):
            result = self.run_theme(name)
            self.assertEqual(result.returncode, 0, result.stderr)

        self.assertEqual(self.tracked(), before)
        for target in (".tmux.conf", ".config/ghostty/config"):
            self.assertFalse((self.home / target).is_symlink())
            self.assertIn("catppuccin-macchiato", (self.home / target).read_text(encoding="utf-8"))

    def test_switch_replaces_old_directory_links_with_real_directories(self) -> None:
        directories = [self.home / ".config/lazydocker", self.home / ".config/superfile"]
        for directory in directories:
            shutil.rmtree(directory)
            directory.symlink_to(self.root / directory.relative_to(self.home))
        (self.root / ".config/lazydocker/config.yml").write_text("tracked\n", encoding="utf-8")
        before = self.tracked()
        (self.home / ".tmux.conf").write_text("mine\n", encoding="utf-8")

        refused = self.run_theme("dark-2026")

        self.assertEqual(refused.returncode, 1)
        self.assertTrue(all(directory.is_symlink() for directory in directories))
        (self.home / ".tmux.conf").unlink()

        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.tracked(), before)
        for directory in directories:
            self.assertFalse(directory.is_symlink())
        self.assertIn("dark-2026", (self.home / ".config/lazydocker/config.yml").read_text(encoding="utf-8"))
        self.assertIn("dark-2026", (self.home / ".config/superfile/config.toml").read_text(encoding="utf-8"))

    def test_switch_refuses_files_it_does_not_own_before_any_write(self) -> None:
        elsewhere = self.home / "elsewhere"
        elsewhere.write_text("mine\n", encoding="utf-8")
        targets = (self.home / ".tmux.conf", self.home / ".config/ghostty/config")
        for refused, other in (targets, reversed(targets)):
            for setup, message in (
                (lambda: refused.write_text("mine\n", encoding="utf-8"), "was not generated by set-theme"),
                (lambda: refused.symlink_to(elsewhere), "is a link that set-theme does not manage"),
                (lambda: refused.symlink_to(self.root / ".tmux/themes"), "is a link that set-theme does not manage"),
            ):
                with self.subTest(target=refused.name, message=message):
                    for path in targets:
                        path.unlink(missing_ok=True)
                    setup()
                    before = refused.read_bytes() if refused.is_file() else None

                    result = self.run_theme("dark-2026")

                    self.assertEqual(result.returncode, 1)
                    self.assertIn(message, result.stderr)
                    self.assertIn("Move it aside", result.stderr)
                    self.assertEqual(refused.read_bytes() if refused.is_file() else None, before)
                    self.assertFalse(other.exists())
                    self.assertFalse(self.state.exists())

    def test_switch_refuses_a_parent_link_into_the_checkout(self) -> None:
        shared = self.root.parent / "shared/ghostty"
        for target in (self.root / ".config/ghostty", shared):
            with self.subTest(target=target):
                shutil.rmtree(self.home / ".config/ghostty", ignore_errors=True)
                (self.home / ".config/ghostty").unlink(missing_ok=True)
                target.mkdir(parents=True, exist_ok=True)
                (self.home / ".config/ghostty").symlink_to(target)
                before = self.tracked()

                result = self.run_theme("dark-2026")

                self.assertEqual(result.returncode, 1)
                self.assertIn("leads into the checkout", result.stderr)
                self.assertEqual(self.tracked(), before)

    def test_bad_selections_are_refused_before_anything_is_saved(self) -> None:
        self.add_theme("half-done", tools=("starship",))
        for name, message in (
            ("../dark-2026", "not a theme name"),
            ("solarized", "Unknown theme 'solarized'"),
            ("half-done", "no file for: LazyGit"),
        ):
            with self.subTest(name=name):
                result = self.run_theme(name)
                self.assertEqual(result.returncode, 1)
                self.assertIn(message, result.stderr)
                self.assertFalse(self.state.exists())

    def test_list_shows_complete_themes_and_marks_the_active_one(self) -> None:
        self.add_theme("half-done", tools=("lazygit",))
        self.assertEqual(self.run_theme("--list").stdout, "* catppuccin-macchiato\n  dark-2026\n")

        self.run_theme("dark-2026")
        self.assertEqual(self.run_theme("--list").stdout, "  catppuccin-macchiato\n* dark-2026\n")

    def test_reapply_uses_the_default_without_saving_it(self) -> None:
        result = self.run_theme()

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Applied theme catppuccin-macchiato", result.stdout)
        self.assertFalse(self.state.exists())
        self.assertEqual(self.exports()["STARSHIP_CONFIG"], f"{self.home}/.config/starship.catppuccin-macchiato.toml")

    def test_reapply_uses_the_saved_theme(self) -> None:
        self.run_theme("dark-2026")
        result = self.run_theme()

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Applied theme dark-2026", result.stdout)

    def test_corrupt_state_blocks_reapply_but_a_name_recovers(self) -> None:
        self.state.parent.mkdir(parents=True)
        self.state.write_text("Dark 2026!\n", encoding="utf-8")

        reapply = self.run_theme()
        self.assertEqual(reapply.returncode, 1)
        self.assertIn("is not a theme name", reapply.stderr)

        recover = self.run_theme("dark-2026")
        self.assertEqual(recover.returncode, 0, recover.stderr)
        self.assertEqual(self.state.read_text(encoding="utf-8"), "dark-2026\n")

    def test_shell_startup_warns_and_uses_the_default_for_unusable_state(self) -> None:
        self.add_theme("half-done", tools=("lazygit",))
        self.state.parent.mkdir(parents=True)
        for saved in ("Dark 2026!", "solarized", "half-done"):
            with self.subTest(saved=saved):
                self.state.write_text(f"{saved}\n", encoding="utf-8")
                result = self.run_theme("--env")
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertIn("warning:", result.stderr)
                self.assertEqual(
                    self.exports()["STARSHIP_CONFIG"], f"{self.home}/.config/starship.catppuccin-macchiato.toml"
                )

    def test_check_passes_when_installed_files_and_shell_match(self) -> None:
        self.run_theme("dark-2026")

        result = self.run_theme("--check", **self.exports())

        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertIn("dark-2026", result.stdout)

    def test_check_reports_drift_without_repairing_it(self) -> None:
        exports = self.exports()
        self.run_theme("dark-2026")
        starship = self.home / ".config/starship.dark-2026.toml"
        starship.unlink()

        result = self.run_theme("--check", **exports)

        self.assertEqual(result.returncode, 1)
        self.assertIn("starship theme file", result.stdout)
        self.assertIn("STARSHIP_CONFIG does not use active theme 'dark-2026'", result.stdout)
        self.assertIn("LG_CONFIG_FILE does not use active theme 'dark-2026'", result.stdout)
        self.assertFalse(starship.exists())

    def test_check_reports_generated_configs_from_another_theme(self) -> None:
        self.run_theme("dark-2026")
        exports = self.exports()
        self.state.write_text("catppuccin-macchiato\n", encoding="utf-8")
        exports = {**exports, **self.exports()}

        result = self.run_theme("--check", **exports)

        self.assertEqual(result.returncode, 1)
        self.assertIn(f"{self.home}/.tmux.conf does not match active theme 'catppuccin-macchiato'", result.stdout)
        self.assertIn(f"{self.home}/.config/ghostty/config does not match active theme", result.stdout)
        self.assertIn("4 problems", result.stdout)

    def test_check_reports_a_copy_that_is_not_the_checkout_file(self) -> None:
        self.run_theme("dark-2026")
        exports = self.exports()
        stale = self.home / ".config/starship.dark-2026.toml"
        stale.unlink()
        stale.write_text("old copy\n", encoding="utf-8")

        result = self.run_theme("--check", **exports)

        self.assertEqual(result.returncode, 1)
        self.assertIn(f"{stale} is not the checkout's file", result.stdout)

    def test_shell_startup_uses_the_default_when_the_theme_is_not_installed(self) -> None:
        self.run_theme("dark-2026")
        (self.home / ".config/starship.dark-2026.toml").unlink()

        result = self.run_theme("--env")

        self.assertIn("warning:", result.stderr)
        self.assertIn("starship.catppuccin-macchiato.toml", result.stdout)

    def test_shell_startup_warns_for_unreadable_state(self) -> None:
        self.state.parent.mkdir(parents=True)
        self.state.write_bytes(b"\xff\xfe\n")

        result = self.run_theme("--env")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("warning:", result.stderr)
        self.assertNotIn("Traceback", result.stderr)
        self.assertIn("starship.catppuccin-macchiato.toml", result.stdout)

    def test_the_tracked_shell_config_names_no_theme(self) -> None:
        zshrc = (REPO_ROOT / ".zshrc").read_text(encoding="utf-8")
        for name in THEMES:
            self.assertNotIn(name, zshrc)
        self.assertNotRegex(zshrc, r"(?m)^export (STARSHIP_CONFIG|LG_CONFIG_FILE)=")

    def test_every_theme_is_complete_in_the_checkout(self) -> None:
        listed = self.run_theme("--list", root=REPO_ROOT).stdout.split()
        self.assertEqual([name for name in listed if name != "*"], list(THEMES))


if __name__ == "__main__":
    unittest.main()
