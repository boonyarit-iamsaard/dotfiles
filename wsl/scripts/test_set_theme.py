#!/usr/bin/env python3
"""CLI tests for the WSL active-theme selector."""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


SCRIPT = Path(__file__).with_name("set-theme")
REPO_ROOT = Path(__file__).resolve().parent.parent
THEMES = (
    "catppuccin-macchiato",
    "catppuccin-mocha",
    "dark-2026",
    "default-dark-modern",
)


class SetThemeTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        fixture = Path(self.temporary.name).resolve()
        self.home = fixture / "home"
        self.state_home = fixture / "state"
        self.root = fixture / "dotfiles/wsl"
        self.home.mkdir()
        (self.root / "config/lazydocker").mkdir(parents=True)
        (self.root / "config/nvim/lua/plugins").mkdir(parents=True)
        (self.root / "config/nvim/lua/themes").mkdir(parents=True)
        (self.root / "config/btop").mkdir(parents=True)
        (self.root / "tmux/.tmux/themes").mkdir(parents=True)
        (self.root / "tmux/.tmux/base.conf").write_text("set -g mouse on\n", encoding="utf-8")
        (self.root / "config/lazydocker/config.yml").write_text(
            "# base\n# >>> theme\n# <<< theme\n", encoding="utf-8"
        )
        (self.root / "config/nvim/lua/plugins/colorscheme.lua").write_text(
            "return {}\n", encoding="utf-8"
        )
        (self.root / "config/btop/btop.conf").write_text(
            'color_theme = "default-dark-modern.theme"\ntheme_background = false\n',
            encoding="utf-8",
        )
        for name in THEMES:
            self.add_theme(name)
        self.link_theme_directories()
        self.state = self.state_home / "dotfiles/theme"

    def add_theme(self, name: str, tools: tuple[str, ...] = ("all",)) -> None:
        files = {
            "starship": f"config/starship.{name}.toml",
            "lazygit": f"config/lazygit/themes/{name}.yml",
            "tmux": f"tmux/.tmux/themes/{'catppuccin' if name == 'catppuccin-mocha' else name}.conf",
            "lazydocker": f"config/lazydocker/themes/{name}.yml",
            "btop": f"config/btop/themes/{name}.theme",
        }
        for tool, relative in files.items():
            if tools != ("all",) and tool not in tools:
                continue
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(f"{name}\n", encoding="utf-8")
        if name not in ("catppuccin-macchiato", "catppuccin-mocha") and tools == ("all",):
            theme_dir = self.root / f"config/nvim/lua/themes/{name}"
            theme_dir.mkdir(parents=True, exist_ok=True)
            (theme_dir / "lazygit.lua").write_text(f"{name}\n", encoding="utf-8")

    def link_theme_directories(self) -> None:
        for home_relative, root_relative in (
            (".config/lazygit/themes", "config/lazygit/themes"),
            (".config/lazydocker/themes", "config/lazydocker/themes"),
            (".config/btop/themes", "config/btop/themes"),
            (".config/nvim/lua/themes", "config/nvim/lua/themes"),
            (".tmux/themes", "tmux/.tmux/themes"),
        ):
            target = self.home / home_relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.symlink_to(self.root / root_relative)
        for name in THEMES:
            source = self.root / f"config/starship.{name}.toml"
            target = self.home / f".config/starship.{name}.toml"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.symlink_to(source)

    def run_theme(self, *args: str, **env: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [str(SCRIPT), "--root", str(self.root), "--home", str(self.home), *args],
            capture_output=True,
            text=True,
            env={**os.environ, "XDG_STATE_HOME": str(self.state_home), **env},
        )

    def test_list_shows_complete_themes_and_marks_the_default(self) -> None:
        result = self.run_theme("--list")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            result.stdout,
            "* catppuccin-macchiato\n  catppuccin-mocha\n  dark-2026\n  default-dark-modern\n",
        )

    def test_apply_generates_every_runtime_config_and_saves_last(self) -> None:
        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.state.read_text(encoding="utf-8"), "dark-2026\n")
        self.assertEqual(
            (self.home / ".tmux.conf").read_text(encoding="utf-8"),
            "# Generated by wsl/scripts/set-theme from wsl/tmux/.tmux/base.conf; edits are overwritten.\n"
            "set -g @theme dark-2026\nsource-file ~/.tmux/base.conf\n",
        )
        lazydocker = (self.home / ".config/lazydocker/config.yml").read_text(encoding="utf-8")
        self.assertIn("# >>> theme: dark-2026\n", lazydocker)
        self.assertIn("dark-2026\n# <<< theme\n", lazydocker)
        self.assertEqual(
            (self.home / ".config/nvim/lua/active_theme.lua").read_text(encoding="utf-8"),
            "-- Generated by wsl/scripts/set-theme from wsl/config/nvim/lua/plugins/colorscheme.lua; edits are overwritten.\n"
            'return { colorscheme = "dark-2026", import = "themes.dark-2026" }\n',
        )
        self.assertEqual(
            (self.home / ".config/btop/btop.conf").read_text(encoding="utf-8"),
            'color_theme = "dark-2026"\n',
        )

    def test_every_theme_selects_the_matching_neovim_and_tmux_variant(self) -> None:
        expected = {
            "catppuccin-macchiato": ('colorscheme = "catppuccin-macchiato", flavour = "macchiato"', "catppuccin-macchiato"),
            "catppuccin-mocha": ('colorscheme = "catppuccin-mocha", flavour = "mocha"', "catppuccin"),
            "dark-2026": ('colorscheme = "dark-2026", import = "themes.dark-2026"', "dark-2026"),
            "default-dark-modern": ('colorscheme = "vscode", import = "themes.default-dark-modern"', "default-dark-modern"),
        }
        for name, (selection, tmux_theme) in expected.items():
            with self.subTest(theme=name):
                result = self.run_theme(name)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertIn(selection, (self.home / ".config/nvim/lua/active_theme.lua").read_text(encoding="utf-8"))
                self.assertIn(f"set -g @theme {tmux_theme}\n", (self.home / ".tmux.conf").read_text(encoding="utf-8"))
                self.assertIn(f'color_theme = "{name}"', (self.home / ".config/btop/btop.conf").read_text(encoding="utf-8"))

    def test_reapply_defaults_without_saving_and_named_apply_recovers_corrupt_state(self) -> None:
        result = self.run_theme()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(self.state.exists())
        self.assertIn("catppuccin-macchiato", result.stdout)

        self.state.parent.mkdir(parents=True)
        self.state.write_text("not a theme!\n", encoding="utf-8")
        self.assertEqual(self.run_theme().returncode, 1)
        recovered = self.run_theme("dark-2026")
        self.assertEqual(recovered.returncode, 0, recovered.stderr)
        self.assertEqual(self.state.read_text(encoding="utf-8"), "dark-2026\n")

    def test_env_and_check_use_the_saved_theme(self) -> None:
        self.assertEqual(self.run_theme("dark-2026").returncode, 0)
        env = self.run_theme("--env")
        self.assertEqual(env.returncode, 0, env.stderr)
        self.assertIn(f"export STARSHIP_CONFIG={self.home}/.config/starship.dark-2026.toml", env.stdout)
        self.assertIn(f"LG_CONFIG_FILE={self.home}/.config/lazygit/config.yml,{self.home}/.config/lazygit/themes/dark-2026.yml", env.stdout)
        checked = self.run_theme(
            "--check",
            STARSHIP_CONFIG=str(self.home / ".config/starship.dark-2026.toml"),
            LG_CONFIG_FILE=f"{self.home}/.config/lazygit/config.yml,{self.home}/.config/lazygit/themes/dark-2026.yml",
        )
        self.assertEqual(checked.returncode, 0, checked.stdout)
        self.assertIn("theme dark-2026: 0 problems", checked.stdout)

    def test_refuses_unmanaged_generated_file_before_writing_anything(self) -> None:
        target = self.home / ".tmux.conf"
        target.write_text("mine\n", encoding="utf-8")

        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 1)
        self.assertIn("was not generated by set-theme", result.stderr)
        self.assertEqual(target.read_text(encoding="utf-8"), "mine\n")
        self.assertFalse((self.home / ".config/lazydocker/config.yml").exists())
        self.assertFalse(self.state.exists())

    def test_migrates_the_old_btop_link_without_writing_to_the_checkout(self) -> None:
        tracked = (self.root / "config/btop/btop.conf").read_text(encoding="utf-8")
        installed = self.home / ".config/btop/btop.conf"
        installed.parent.mkdir(parents=True, exist_ok=True)
        installed.symlink_to(self.root / "config/btop/btop.conf")

        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(installed.is_symlink())
        self.assertEqual((self.root / "config/btop/btop.conf").read_text(encoding="utf-8"), tracked)
        self.assertIn('theme_background = false', installed.read_text(encoding="utf-8"))

    def test_links_a_matching_real_btop_theme_to_the_checkout(self) -> None:
        themes = self.home / ".config/btop/themes"
        themes.unlink()
        themes.mkdir()
        installed = themes / "dark-2026.theme"
        tracked = self.root / "config/btop/themes/dark-2026.theme"
        installed.write_bytes(tracked.read_bytes())

        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(installed.is_symlink())
        self.assertEqual(installed.resolve(), tracked.resolve())

    def test_refuses_an_unmanaged_parent_link_before_writing_anything(self) -> None:
        lazydocker = self.home / ".config/lazydocker"
        shutil.rmtree(lazydocker)
        outside = Path(self.temporary.name) / "unmanaged"
        outside.mkdir()
        lazydocker.symlink_to(outside)

        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 1)
        self.assertIn("parent link that set-theme does not manage", result.stderr)
        self.assertFalse((self.home / ".tmux.conf").exists())
        self.assertFalse(self.state.exists())

    def test_refuses_a_btop_directory_before_writing_anything(self) -> None:
        target = self.home / ".config/btop/btop.conf"
        target.mkdir()

        result = self.run_theme("dark-2026")

        self.assertEqual(result.returncode, 1)
        self.assertIn("is not a file", result.stderr)
        self.assertTrue(target.is_dir())
        self.assertFalse((self.home / ".tmux.conf").exists())
        self.assertFalse(self.state.exists())

    def test_unknown_and_incomplete_themes_are_refused(self) -> None:
        self.add_theme("half-done", tools=("lazygit",))

        for name, message in (("solarized", "Unknown theme"), ("half-done", "no file for"), ("../dark-2026", "not a theme name")):
            with self.subTest(name=name):
                result = self.run_theme(name)
                self.assertEqual(result.returncode, 1)
                self.assertIn(message, result.stderr)
                self.assertFalse(self.state.exists())


class FreshInstallTest(unittest.TestCase):
    """Apply every theme against the real WSL checkout without touching Git."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        fixture = Path(temporary.name).resolve()
        self.home = fixture / "home"
        self.state_home = fixture / "state"
        self.home.mkdir()
        for home_relative, root_relative in (
            (".config/lazygit/themes", "config/lazygit/themes"),
            (".config/lazydocker/themes", "config/lazydocker/themes"),
            (".config/btop/themes", "config/btop/themes"),
            (".config/nvim/lua/themes", "config/nvim/lua/themes"),
            (".tmux/themes", "tmux/.tmux/themes"),
        ):
            target = self.home / home_relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.symlink_to(REPO_ROOT / root_relative)
        for name in THEMES:
            target = self.home / f".config/starship.{name}.toml"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.symlink_to(REPO_ROOT / f"config/starship.{name}.toml")
        (self.home / ".config/lazygit/config.yml").symlink_to(
            REPO_ROOT / "config/lazygit/config.yml"
        )
        (self.home / ".tmux/base.conf").symlink_to(REPO_ROOT / "tmux/.tmux/base.conf")

    def run_in_home(self, *args: str, **env: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [str(SCRIPT), "--root", str(REPO_ROOT), "--home", str(self.home), *args],
            capture_output=True,
            text=True,
            env={**os.environ, "XDG_STATE_HOME": str(self.state_home), **env},
        )

    def checkout_state(self) -> tuple[str, str]:
        git = ("git", "-C", str(REPO_ROOT))
        status = subprocess.run(
            [*git, "status", "--porcelain", "--ignored", "--untracked-files=all"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        diff = subprocess.run(
            [*git, "diff", "HEAD", "--binary", "--", "."],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        return status, diff

    def test_install_and_every_theme_keep_the_checkout_clean(self) -> None:
        before = self.checkout_state()
        initial = self.run_in_home()
        self.assertEqual(initial.returncode, 0, initial.stderr)
        self.assertFalse((self.state_home / "dotfiles/theme").exists())

        for name in THEMES:
            with self.subTest(theme=name):
                applied = self.run_in_home(name)
                self.assertEqual(applied.returncode, 0, applied.stderr)
                exports = self.run_in_home("--env").stdout.splitlines()
                environment = {
                    line.split("=", 1)[0].removeprefix("export "): line.split("=", 1)[1].strip("'")
                    for line in exports
                }
                checked = self.run_in_home("--check", **environment)
                self.assertEqual(checked.returncode, 0, checked.stdout)
                self.assertIn(f"theme {name}: 0 problems", checked.stdout)
                self.assertEqual(self.checkout_state(), before)


if __name__ == "__main__":
    unittest.main()
